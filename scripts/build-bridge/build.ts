import path from 'node:path'
import { build } from 'esbuild'

const root = path.resolve(import.meta.dirname, '../..')

/** Where the committed bridge bundle lives: the plugin's `bin/`, run with plain Node. */
export const BRIDGE_BUNDLE = path.join(root, 'plugin/bin/dm-bridge.mjs')

/** Where the committed launcher bundle lives: `dm` runs it through the terminal shim. */
export const LAUNCHER_BUNDLE = path.join(root, 'plugin/bin/dm.mjs')

/** Where the committed hooks bundle lives: `hooks/hooks.json` runs it for each plugin hook. */
export const HOOKS_BUNDLE = path.join(root, 'plugin/hooks/dm-hooks.mjs')

/** One self-contained ESM file for plain Node, so the plugin root needs no `package.json`. */
async function bundle(entry: string, outfile: string) {
  await build({
    entryPoints: [path.join(root, entry)],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node24',
    legalComments: 'none',
    logLevel: 'warning',
    banner: {
      js: `// Generated by \`pnpm build:bridge\` from ${path.dirname(entry)}. Do not edit.`
    }
  })
}

/** Bundles the bridge with the MCP SDK inlined, so no dependency install runs. */
export async function buildBridge(outfile = BRIDGE_BUNDLE) {
  await bundle('src/bridge/main.ts', outfile)
}

/** Bundles the `dm` launcher. */
export async function buildLauncher(outfile = LAUNCHER_BUNDLE) {
  await bundle('src/launcher/main.ts', outfile)
}

/** Bundles the plugin hooks (PreToolUse, Stop, SessionStart). */
export async function buildHooks(outfile = HOOKS_BUNDLE) {
  await bundle('src/hooks/main.ts', outfile)
}

if (import.meta.main) {
  await buildBridge()
  await buildLauncher()
  await buildHooks()
}
