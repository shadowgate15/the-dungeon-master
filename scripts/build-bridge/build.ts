import path from 'node:path'
import { build } from 'esbuild'

const root = path.resolve(import.meta.dirname, '../..')

/** Where the committed bridge bundle lives: the plugin's `bin/`, run with plain Node. */
export const BRIDGE_BUNDLE = path.join(root, 'plugin/bin/dm-bridge.mjs')

/**
 * Bundles the bridge into one ESM file with the MCP SDK inlined, so the plugin root needs no
 * `package.json` and no dependency install.
 */
export async function buildBridge(outfile = BRIDGE_BUNDLE) {
  await build({
    entryPoints: [path.join(root, 'src/bridge/main.ts')],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node24',
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: '// Generated by `pnpm build:bridge` from src/bridge. Do not edit.' }
  })
}

if (import.meta.main) await buildBridge()
